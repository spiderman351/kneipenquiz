// Hält die App-Dateien offline vor. Erst Netz, dann Cache, damit Änderungen sofort ankommen.
// "no-cache" fragt bei jedem Laden kurz bei GitHub nach, ob es eine neue Version gibt,
// statt bis zu 10 Minuten eine zwischengespeicherte Datei zu nehmen.
const CACHE = 'kneipenquiz-v2';
const SHELL = ['./', 'index.html', 'style.css', 'app.js', 'questions.js', 'config.js', 'manifest.webmanifest', 'icon.svg', 'icon-192.png', 'icon-512.png'];

self.addEventListener('install', e => {
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(SHELL)).catch(() => {}).then(() => self.skipWaiting()));
});

self.addEventListener('activate', e => {
  e.waitUntil(
    caches.keys()
      .then(keys => Promise.all(keys.filter(k => k !== CACHE).map(k => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', e => {
  const url = new URL(e.request.url);
  if (e.request.method !== 'GET' || url.origin !== location.origin) return;
  e.respondWith(
    fetch(e.request.url, { cache: 'no-cache', credentials: 'same-origin' })
      .then(res => {
        const copy = res.clone();
        caches.open(CACHE).then(c => c.put(e.request, copy));
        return res;
      })
      .catch(() => caches.match(e.request, { ignoreSearch: true }))
  );
});
